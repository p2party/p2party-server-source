import { expect, test } from "bun:test";
import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  freshDatabase,
  throwawayServerUrl,
  type ThrowawayDatabase,
} from "./db/throwawayPostgres";
import { bytes, ledgerConfig } from "../src/ledger/config";
import { ledgerRpc } from "../src/ledger/rpc";
import { LedgerStore } from "../src/ledger/store";
import { verifyPeer } from "../src/ledger/verifyPeer";

const verifier = process.env.P2PARTY_TEST_LEDGER_VERIFIER;
const fixture = process.env.P2PARTY_TEST_LEDGER_FIXTURE;
const databaseTest = test.skipIf(!verifier || !fixture || !throwawayServerUrl);
const wire = (s: string) => bytes(s, (s.length - 2) / 2);

function fixtureGenesis(dir: string, expanded: boolean) {
  const data = JSON.parse(
    execFileSync(fixture!, expanded ? ["--extended-suites"] : [], {
      encoding: "utf8",
      timeout: 20000,
    }),
  ) as {
    chainId: string;
    inputId: string;
    commitment: string;
    first: string;
    second: string;
  };
  const suites = expanded ? [1, 2, 3, 4] : [1, 2];
  const genesis = join(dir, "genesis.json");
  writeFileSync(
    genesis,
    JSON.stringify({
      version: 1,
      chainId: data.chainId,
      rpcChainId: 8123,
      spendSuites: suites,
      receiveSuites: suites,
      units: [
        {
          id: data.inputId,
          weight: "0x8",
          suite: expanded ? 3 : 1,
          commitment: data.commitment,
        },
      ],
    }),
  );
  const settings = ledgerConfig({
    LEDGER_ENABLED: "true",
    LEDGER_VERIFIER: verifier,
    LEDGER_CHAIN_ID: data.chainId,
    LEDGER_GENESIS_FILE: genesis,
  })!;
  return { data, settings };
}

databaseTest(
  "pre-upgrade database preserves both legacy signed receipts and validates the new constraints exactly once",
  async () => {
    const dir = mkdtempSync(join(tmpdir(), "p2party-schema-"));
    let db: ThrowawayDatabase | undefined, store: LedgerStore | undefined;
    try {
      const { data, settings } = fixtureGenesis(dir, false);
      db = await freshDatabase([]);
      store = new LedgerStore(settings, db.url);
      await store.initialize();
      // These are the constraints generated by the two-suite production schema.
      await db.client.query(`
      ALTER TABLE p2party_ledger.units DROP CONSTRAINT units_known_suite_v2,
        ADD CONSTRAINT units_suite_check CHECK (suite IN (1,2));
      ALTER TABLE p2party_ledger.transfers DROP CONSTRAINT transfers_known_size_v2,
        ADD CONSTRAINT transfers_wire_check CHECK (octet_length(wire) IN (5505,16516));
    `);
      const first = await store.submit(wire(data.first)),
        second = await store.submit(wire(data.second));
      const before = [await store.transfer(1n), await store.transfer(2n)];
      expect(before.map((r) => r?.id)).toEqual([first, second]);
      const finalId = bytes(before[1]!.outputId, 64);
      const balance = await store.unit(finalId);
      expect(balance).toMatchObject({
        weight: "0x8",
        suite: 1,
        spentHeight: null,
      });
      let constraintIds: string[] | undefined;
      for (let restart = 0; restart < 2; restart++) {
        await store.close();
        store = new LedgerStore(settings, db.url);
        await store.initialize();
        expect(await store.head()).toEqual({
          chainId: data.chainId,
          height: "0x2",
        });
        expect([await store.transfer(1n), await store.transfer(2n)]).toEqual(
          before,
        );
        expect(await store.unit(finalId)).toEqual(balance);
        const { rows } = await db.client.query<{
          conname: string;
          oid: string;
          convalidated: boolean;
        }>(`
        SELECT conname, oid::text, convalidated FROM pg_constraint
        WHERE conrelid IN ('p2party_ledger.units'::regclass, 'p2party_ledger.transfers'::regclass)
          AND conname IN ('units_suite_check','transfers_wire_check','units_known_suite_v2','transfers_known_size_v2')
        ORDER BY conname
      `);
        expect(rows.map((row) => row.conname)).toEqual([
          "transfers_known_size_v2",
          "units_known_suite_v2",
        ]);
        expect(rows.every((row) => row.convalidated)).toBe(true);
        if (constraintIds)
          expect(rows.map((row) => row.oid)).toEqual(constraintIds);
        constraintIds = rows.map((row) => row.oid);
      }
      await expect(
        db.client.query(
          "UPDATE p2party_ledger.units SET suite=5 WHERE created=0",
        ),
      ).rejects.toThrow("units_known_suite_v2");
      await expect(
        db.client.query(
          "UPDATE p2party_ledger.transfers SET wire='\\x00' WHERE height=1",
        ),
      ).rejects.toThrow("transfers_known_size_v2");
      expect(await store.transfer(1n)).toEqual(before[0]);
    } finally {
      await store?.close();
      await db?.drop();
      rmSync(dir, { recursive: true, force: true });
    }
  },
  30000,
);

test.skipIf(process.env.P2PARTY_TEST_EXTENDED_LEDGER !== "1")(
  "a four-suite replica replays ML-DSA-87 into SLH-DSA-SHAKE-256s and back to ML-DSA-65",
  async () => {
    if (!throwawayServerUrl || !verifier || !fixture)
      throw new Error(
        "Expanded ledger tests require a throwaway PostgreSQL server and native verifier and fixture binaries.",
      );
    const dir = mkdtempSync(join(tmpdir(), "p2party-agile-replica-"));
    const databases: ThrowawayDatabase[] = [],
      stores: LedgerStore[] = [];
    let peer: ReturnType<typeof Bun.serve> | undefined;
    try {
      const { data, settings } = fixtureGenesis(dir, true);
      for (const role of ["writer", "replica"] as const) {
        const db = await freshDatabase([]);
        databases.push(db);
        const store = new LedgerStore(settings, db.url);
        stores.push(store);
        await store.initialize(role);
      }
      const [writer, replica] = stores;
      const first = await writer!.submit(wire(data.first)),
        second = await writer!.submit(wire(data.second));
      peer = Bun.serve({
        hostname: "127.0.0.1",
        port: 0,
        fetch: ledgerRpc(writer!),
      });
      const endpoint = new URL("/rpc", peer.url).href;
      const checkpoint = await verifyPeer(replica!, endpoint);
      expect(checkpoint.height).toBe("0x2");
      expect(await verifyPeer(replica!, endpoint)).toEqual(checkpoint);
      const one = await replica!.transfer(1n),
        two = await replica!.transfer(2n);
      expect(one).toEqual(await writer!.transfer(1n));
      expect(two).toEqual(await writer!.transfer(2n));
      expect(one).toMatchObject({
        id: first,
        inputId: data.inputId,
        wire: data.first,
      });
      expect(two).toMatchObject({
        id: second,
        inputId: one!.outputId,
        wire: data.second,
      });
      expect(wire(two!.wire).byteLength).toBe(30100);
      expect(await replica!.unit(bytes(data.inputId, 64))).toMatchObject({
        suite: 3,
        spentHeight: "0x1",
      });
      expect(await replica!.unit(bytes(one!.outputId, 64))).toMatchObject({
        suite: 4,
        spentHeight: "0x2",
      });
      expect(await replica!.unit(bytes(two!.outputId, 64))).toMatchObject({
        suite: 1,
        weight: "0x8",
        spentHeight: null,
      });
    } finally {
      await peer?.stop(true);
      await Promise.all(stores.map((s) => s.close()));
      await Promise.all(databases.map((db) => db.drop()));
      rmSync(dir, { recursive: true, force: true });
    }
  },
  30000,
);
