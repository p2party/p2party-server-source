CREATE TABLE room (
  id TEXT PRIMARY KEY,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  identifier TEXT NOT NULL UNIQUE
);

CREATE TABLE peer (
  id TEXT PRIMARY KEY,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lastPing BIGINT NOT NULL,
  publicKey TEXT NOT NULL UNIQUE
);

CREATE TABLE challenge (
  id TEXT PRIMARY KEY,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  nonce TEXT NOT NULL UNIQUE,
  signature TEXT UNIQUE,
  peerId TEXT NOT NULL,
  FOREIGN KEY (peerId) REFERENCES peer(id) ON DELETE CASCADE
);

CREATE TABLE _RoomToPeer (
  A TEXT NOT NULL,
  B TEXT NOT NULL,
  PRIMARY KEY (A, B),
  FOREIGN KEY (A) REFERENCES room(id) ON DELETE CASCADE,
  FOREIGN KEY (B) REFERENCES peer(id) ON DELETE CASCADE
);
