-- Enable extension for UUID generation
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

CREATE TABLE room (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  createdAt TIMESTAMPTZ NOT NULL DEFAULT now(),
  updatedAt TIMESTAMPTZ NOT NULL DEFAULT now(),
  identifier TEXT NOT NULL UNIQUE
);

CREATE TABLE peer (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  createdAt TIMESTAMPTZ NOT NULL DEFAULT now(),
  updatedAt TIMESTAMPTZ NOT NULL DEFAULT now(),
  lastPing BIGINT NOT NULL,
  publicKey TEXT NOT NULL UNIQUE
);

CREATE TABLE challenge (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  createdAt TIMESTAMPTZ NOT NULL DEFAULT now(),
  updatedAt TIMESTAMPTZ NOT NULL DEFAULT now(),
  nonce TEXT NOT NULL UNIQUE,
  signature TEXT UNIQUE,
  peerId UUID NOT NULL REFERENCES peer(id) ON DELETE CASCADE
);

CREATE TABLE _RoomToPeer (
  A UUID NOT NULL REFERENCES room(id) ON DELETE CASCADE,
  B UUID NOT NULL REFERENCES peer(id) ON DELETE CASCADE,
  PRIMARY KEY (A, B)
);
